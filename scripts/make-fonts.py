"""Builds the app's bundled fonts (needs Python 3 + fontTools: pip install fonttools).

  python scripts/make-fonts.py <lucide-static package dir> <PlusJakartaSans[wght].ttf>

- Plus Jakarta Sans (OFL, github.com/google/fonts ofl/plusjakartasans): the variable font is cut into the four static
  weights the app uses. Android picks a custom font by file name, so each weight is its own family.
- Lucide icons (ISC, npm lucide-static, font/lucide.ttf): subset to ICON_NAMES only, and src/ui/iconMap.ts is
  regenerated. To add an icon: append its Lucide name below and re-run.
"""
import json
import os
import sys

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS_DIR = os.path.join(ROOT, 'android', 'app', 'src', 'main', 'assets', 'fonts')
ICON_MAP = os.path.join(ROOT, 'src', 'ui', 'iconMap.ts')

WEIGHTS = {'Regular': 400, 'Medium': 500, 'SemiBold': 600, 'Bold': 700}

ICON_NAMES = [
    'receipt-text', 'history', 'chart-column', 'store', 'phone', 'bike', 'clock', 'timer', 'chef-hat',
    'package-check', 'check', 'circle-check', 'x', 'chevron-right', 'chevron-left', 'minus', 'plus', 'bell',
    'bell-ring', 'volume-2', 'wifi', 'wifi-off', 'log-out', 'calendar-clock', 'info', 'triangle-alert', 'map-pin',
    'user-round', 'shield-check', 'battery-charging', 'smartphone', 'refresh-cw', 'inbox', 'ban', 'circle-x',
    'power', 'settings', 'wallet', 'utensils', 'key-round', 'hand-platter', 'indian-rupee', 'trending-up', 'hash',
    'message-square-text', 'badge-check',
]


def rename(font, family):
    for record in font['name'].names:
        if record.nameID in (1, 4, 6, 16):
            record.string = family
        elif record.nameID in (2, 17):
            record.string = 'Regular'


def build_text_fonts(variable_path):
    for style, weight in WEIGHTS.items():
        font = instancer.instantiateVariableFont(TTFont(variable_path), {'wght': weight})
        family = f'PlusJakartaSans-{style}'
        rename(font, family)
        font['OS/2'].usWeightClass = weight
        font.save(os.path.join(FONTS_DIR, f'{family}.ttf'))


def build_icon_font(lucide_dir):
    with open(os.path.join(lucide_dir, 'font', 'codepoints.json'), encoding='utf-8') as f:
        codepoints = json.load(f)
    missing = [n for n in ICON_NAMES if n not in codepoints]
    if missing:
        sys.exit(f'unknown Lucide icon name(s): {", ".join(missing)}')

    font = TTFont(os.path.join(lucide_dir, 'font', 'lucide.ttf'))
    options = subset.Options()
    options.layout_features = []
    options.name_IDs = ['*']
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=[codepoints[n] for n in ICON_NAMES])
    subsetter.subset(font)
    rename(font, 'QVIcons')
    font.save(os.path.join(FONTS_DIR, 'QVIcons.ttf'))

    lines = [
        '// Generated by scripts/make-fonts.py from Lucide (ISC). Do not edit by hand.',
        'export const ICONS = {',
        *[f"  '{n}': '\\u{codepoints[n]:04x}'," for n in ICON_NAMES],
        '} as const;',
        '',
    ]
    with open(ICON_MAP, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    os.makedirs(FONTS_DIR, exist_ok=True)
    build_text_fonts(sys.argv[2])
    build_icon_font(sys.argv[1])
    print('fonts written to', os.path.relpath(FONTS_DIR, ROOT))


if __name__ == '__main__':
    main()
